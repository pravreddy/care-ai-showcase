#!/bin/bash
# ============================================================
# Care AI - Free SSL Setup (Let's Encrypt)
#
# Run this AFTER:
#   1. DNS points to this server (ping careaisoftware.co.uk → your IP)
#   2. docker compose up -d is running on HTTP
#
# Usage:
#   chmod +x ssl-setup.sh
#   ./ssl-setup.sh careaisoftware.co.uk
#
# What it does:
#   1. Gets free SSL cert from Let's Encrypt
#   2. Copies cert + SSL nginx config into ./ssl/
#   3. Creates docker-compose.override.yml to mount SSL config
#   4. Restarts everything with HTTPS
#   5. Sets up auto-renewal (every 60 days, zero maintenance)
# ============================================================

set -euo pipefail

DOMAIN=${1:-}
DEPLOY_DIR="/home/deploy/careai"

if [ -z "$DOMAIN" ]; then
    echo "Usage: ./ssl-setup.sh careaisoftware.co.uk"
    exit 1
fi

echo ""
echo "============================================"
echo "  Setting up SSL for: $DOMAIN"
echo "============================================"
echo ""

# --- Step 1: Install certbot ---
echo "[1/5] Installing Certbot..."
sudo apt-get update -qq
sudo apt-get install -y -qq certbot
echo "  ✓ Certbot installed"

# --- Step 2: Stop frontend to free port 80 ---
echo "[2/5] Getting SSL certificate from Let's Encrypt..."
cd "$DEPLOY_DIR"
docker compose stop frontend

# Get the certificate (standalone mode binds to port 80 for verification)
sudo certbot certonly \
    --standalone \
    --non-interactive \
    --agree-tos \
    --email admin@${DOMAIN} \
    --domain ${DOMAIN} \
    --domain www.${DOMAIN}

echo "  ✓ Certificate obtained"

# --- Step 3: Copy certs to ssl directory ---
echo "[3/5] Installing certificates..."
mkdir -p "$DEPLOY_DIR/ssl"

sudo cp /etc/letsencrypt/live/${DOMAIN}/fullchain.pem "$DEPLOY_DIR/ssl/"
sudo cp /etc/letsencrypt/live/${DOMAIN}/privkey.pem "$DEPLOY_DIR/ssl/"
sudo chown deploy:deploy "$DEPLOY_DIR/ssl/"*.pem
chmod 600 "$DEPLOY_DIR/ssl/"*.pem

echo "  ✓ Certificates installed in $DEPLOY_DIR/ssl/"

# --- Step 4: Create SSL nginx config ---
echo "[4/5] Creating HTTPS nginx config..."

cat > "$DEPLOY_DIR/ssl/default.conf" << 'NGINXEOF'
# ============================================================
# Care AI Frontend - Nginx HTTPS Configuration
# Auto-generated by ssl-setup.sh — do not edit manually
# ============================================================

upstream backend {
    server careai-api:8000;
    keepalive 32;
}

# Redirect HTTP → HTTPS
server {
    listen 80;
    server_name _;
    return 301 https://$host$request_uri;
}

# HTTPS server
server {
    listen 443 ssl http2;
    server_name _;

    # --- SSL certificates (Let's Encrypt) ---
    ssl_certificate /etc/nginx/ssl/fullchain.pem;
    ssl_certificate_key /etc/nginx/ssl/privkey.pem;

    # --- Modern SSL settings ---
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384;
    ssl_prefer_server_ciphers off;
    ssl_session_cache shared:SSL:10m;
    ssl_session_timeout 1d;

    # --- HSTS (tell browsers to always use HTTPS) ---
    add_header Strict-Transport-Security "max-age=63072000; includeSubDomains" always;

    # --- Security headers ---
    add_header X-Frame-Options "SAMEORIGIN" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header X-XSS-Protection "1; mode=block" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;
    add_header Permissions-Policy "camera=(), microphone=(self), geolocation=()" always;

    client_max_body_size 500M;

    # --- Proxy /api to backend ---
    location /api/ {
        proxy_pass http://backend;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
        proxy_connect_timeout 30s;
        proxy_send_timeout 120s;
        proxy_read_timeout 120s;
        proxy_buffering off;
    }

    location /health {
        proxy_pass http://backend/health;
        proxy_set_header Host $host;
    }

    location /ping {
        proxy_pass http://backend/ping;
        proxy_set_header Host $host;
    }

    # --- React SPA ---
    location / {
        root /usr/share/nginx/html;
        index index.html;
        try_files $uri $uri/ /index.html;

        location ~* \.(js|css|png|jpg|jpeg|gif|ico|svg|woff|woff2|ttf|eot)$ {
            expires 1y;
            add_header Cache-Control "public, immutable";
        }

        location = /index.html {
            expires -1;
            add_header Cache-Control "no-store, no-cache, must-revalidate";
        }
    }

    gzip on;
    gzip_vary on;
    gzip_min_length 1024;
    gzip_types text/plain text/css text/javascript application/javascript application/json application/xml image/svg+xml;
}
NGINXEOF

# Create docker-compose override to mount the SSL nginx config
cat > "$DEPLOY_DIR/docker-compose.override.yml" << 'OVERRIDEEOF'
# Auto-generated by ssl-setup.sh — mounts SSL nginx config
# docker compose automatically merges this with docker-compose.yml
services:
  frontend:
    volumes:
      - ./ssl:/etc/nginx/ssl:ro
      - ./ssl/default.conf:/etc/nginx/conf.d/default.conf:ro
OVERRIDEEOF

echo "  ✓ HTTPS nginx config created"
echo "  ✓ docker-compose.override.yml created"

# --- Step 5: Restart with SSL ---
echo "[5/5] Restarting with HTTPS..."
cd "$DEPLOY_DIR"
docker compose up -d
echo "  ✓ All services restarted with HTTPS"

# --- Setup auto-renewal hook ---
echo ""
echo "Setting up auto-renewal..."
sudo mkdir -p /etc/letsencrypt/renewal-hooks/deploy

sudo bash -c "cat > /etc/letsencrypt/renewal-hooks/deploy/careai-reload.sh << 'HOOKEOF'
#!/bin/bash
# Auto-renewal hook: copy new certs and reload nginx
DEPLOY_DIR=/home/deploy/careai
DOMAIN=${DOMAIN}
cp /etc/letsencrypt/live/\${DOMAIN}/fullchain.pem \${DEPLOY_DIR}/ssl/
cp /etc/letsencrypt/live/\${DOMAIN}/privkey.pem \${DEPLOY_DIR}/ssl/
chown deploy:deploy \${DEPLOY_DIR}/ssl/*.pem
chmod 600 \${DEPLOY_DIR}/ssl/*.pem
docker exec careai-frontend nginx -s reload 2>/dev/null || true
HOOKEOF"

sudo chmod +x /etc/letsencrypt/renewal-hooks/deploy/careai-reload.sh

# Test the renewal timer
sudo certbot renew --dry-run 2>/dev/null && echo "  ✓ Auto-renewal test passed" || echo "  ⚠ Auto-renewal dry-run failed (non-critical)"

echo ""
echo "============================================"
echo "  ✅ SSL Setup Complete!"
echo "============================================"
echo ""
echo "  🔒 https://${DOMAIN} is now live"
echo "  🔒 https://www.${DOMAIN} also works"
echo ""
echo "  Auto-renewal: Let's Encrypt renews every"
echo "  60 days and reloads Nginx automatically."
echo ""
echo "  Test: curl https://${DOMAIN}/ping"
echo "============================================"
